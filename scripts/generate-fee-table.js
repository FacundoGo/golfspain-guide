#!/usr/bin/env node
// Writes the "green fees at the 27 courses in our guide" table into both green fees posts,
// using the course directory (/en/courses/, /es/courses/) as the single source of truth.
//
// Usage (from the repo root, after changing prices in the directory):
//   node scripts/generate-fee-table.js
//
// The table lives between <!-- FEE-TABLE:START --> and <!-- FEE-TABLE:END --> in each post;
// everything between the markers is replaced on every run.

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

const POSTS = {
  en: {
    file: 'en/blog/golf-green-fees-spain-2026/index.html',
    directory: 'en/courses/index.html',
    heading: '2026 green fees at the 27 courses in our guide',
    intro: 'Every course we cover, with the visitor green fee from its club guide. Open a course for seasonal rates, what\'s included and how to book. Prices marked ≈ or "dynamic" are indicative and change with demand.',
    cols: ['Course', 'Area', 'Holes', 'Visitor green fee'],
    pp: 'pitch & putt',
  },
  es: {
    file: 'es/blog/green-fees-golf-espana-2026/index.html',
    directory: 'es/courses/index.html',
    heading: 'Green fees 2026 de los 27 campos de la guía',
    intro: 'Todos los campos que cubrimos, con el green fee de visitante de su ficha. Abre cada campo para ver tarifas por temporada, qué incluye y cómo reservar. Los precios con ≈ o "dinámico" son orientativos y cambian según la demanda.',
    cols: ['Campo', 'Zona', 'Hoyos', 'Green fee visitante'],
    pp: 'pitch & putt',
  },
};
const REGION = { valencia: 'Valencia', alicante: 'Alicante', castellon: 'Castellón', barcelona: 'Barcelona', toledo: 'Toledo' };
const REGION_ORDER = ['valencia', 'alicante', 'castellon', 'barcelona', 'toledo'];

function readClubs(file) {
  const s = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const i = s.indexOf('[', s.indexOf('var CLUBS = ['));
  let depth = 0, j = i;
  for (; j < s.length; j++) {
    if (s[j] === '[') depth++;
    else if (s[j] === ']' && --depth === 0) break;
  }
  return eval(s.slice(i, j + 1));   // trusted: our own directory page
}

for (const [lang, p] of Object.entries(POSTS)) {
  const clubs = readClubs(p.directory).sort((a, b) =>
    REGION_ORDER.indexOf(a.region) - REGION_ORDER.indexOf(b.region) ||
    (a.greenFeeMin ?? 999) - (b.greenFeeMin ?? 999));

  const rows = clubs.map(c => {
    const holes = /pitch/i.test(c.type) ? `${c.holes} (${p.pp})` : String(c.holes);
    return `          <tr>
            <td data-label="${p.cols[0]}"><strong><a href="${c.url}">${c.name}</a></strong></td>
            <td data-label="${p.cols[1]}">${c.city}, ${REGION[c.region] || c.region}</td>
            <td data-label="${p.cols[2]}">${holes}</td>
            <td data-label="${p.cols[3]}" class="price-cell">${c.greenFeeDisplay}</td>
          </tr>`;
  }).join('\n');

  const block = `<!-- FEE-TABLE:START (generated by scripts/generate-fee-table.js — do not edit by hand) -->
    <h2>${p.heading}</h2>

    <p>${p.intro}</p>

    <div class="fee-table-wrap">
      <table class="fee-table">
        <thead>
          <tr>
            ${p.cols.map(c => `<th>${c}</th>`).join('\n            ')}
          </tr>
        </thead>
        <tbody>
${rows}
        </tbody>
      </table>
    </div>
    <!-- FEE-TABLE:END -->`;

  const file = path.join(ROOT, p.file);
  let html = fs.readFileSync(file, 'utf8');
  const re = /<!-- FEE-TABLE:START[\s\S]*?<!-- FEE-TABLE:END -->/;
  if (!re.test(html)) throw new Error(`${p.file}: FEE-TABLE markers not found`);
  html = html.replace(re, block);
  fs.writeFileSync(file, html);
  console.log(`${p.file}: ${clubs.length} courses`);
}
